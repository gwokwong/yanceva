def deliverable_path(order_id: str) -> str:
    return os.path.join(Config.UPLOAD_FOLDER, 'orders', order_id, 'deliverable.html')


def save_deliverable(order_id: str, html_content: str) -> str:
    path = deliverable_path(order_id)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(html_content)
    logger.info(f"交付物已保存: {path}")
    return path
