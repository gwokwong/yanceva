def _sparkline_svg(values: List[Optional[float]], width: int = 560, height: int = 90,
                   color: str = "#FF4500", empty_label: str = "") -> str:
    """把数值序列渲染成折线 SVG（None 断点跳过）。"""

    nums = [(i, v) for i, v in enumerate(values)
            if isinstance(v, (int, float)) and not isinstance(v, bool)]
    if len(nums) < 2:
        return f'<div class="chart-empty">{_CHROME.get("zh", {}).get("insufficient")}</div>'
    lo = min(v for _, v in nums)
    hi = max(v for _, v in nums)
    span = (hi - lo) or 1.0
    step_x = width / (len(nums) - 1)
    points = " ".join(
        f"{i * step_x:.1f},{height - 8 - ((v - lo) / span) * (height - 16):.1f}"
        for i, v in nums
    )
    return (
        f'<svg viewBox="0 0 {width} {height}" class="spark" preserveAspectRatio="none">'
        f'<polyline fill="none" stroke="{color}" stroke-width="2.5" points="{points}"/>'
        f'</svg>'
    )


def _metric_charts(series: List[Dict[str, Any]], t: Dict[str, str]) -> str:
    volumes = [(s.get("posts") or 0) + (s.get("comments") or 0) for s in series]
    sentiments = [s.get("sentiment_avg") for s in series]
    intents = [s.get("purchase_intent_avg") for s in series]

    def last(values):
        nums = [v for v in values if isinstance(v, (int, float))]
        return f"{nums[-1]:.2f}" if nums else "—"

    charts = [
        (t["volume"], _sparkline_svg(volumes, empty_label=t["insufficient"]), f'{t["recent"]} {last(volumes)}'),
        (t["sentiment"], _sparkline_svg(sentiments, empty_label=t["insufficient"]), f'{t["recent"]} {last(sentiments)}'),
        (t["intent"], _sparkline_svg(intents, empty_label=t["insufficient"]), f'{t["recent"]} {last(intents)}'),
    ]
    rows = "".join(
        f'<div class="chart-card"><h4>{title}</h4>{svg}'
        f'<div class="chart-meta">{meta}</div></div>'
        for title, svg, meta in charts
    )
    return f'<div class="chart-grid">{rows}</div>'


def _metric_table(series: List[Dict[str, Any]], t: Dict[str, str]) -> str:
    if not series:
        return ""
    rows = []
    for s in series[-24:]:
        sentiment = "—" if s.get("sentiment_avg") is None else f"{s['sentiment_avg']:+.2f}"
        intent = "—" if s.get("purchase_intent_avg") is None else f"{s['purchase_intent_avg']:.2f}"
        rows.append(
            f"<tr><td>{s.get('round')}</td><td>{s.get('posts', 0)}</td>"
            f"<td>{s.get('comments', 0)}</td><td>{s.get('active_agents', 0)}</td>"
            f"<td>{sentiment}</td><td>{intent}</td></tr>"
        )
    headers = (
        f'<tr><th>{t["round"]}</th><th>{t["posts"]}</th><th>{t["comments"]}</th>'
        f'<th>{t["agents"]}</th><th>{t["sentiment"].split("（")[0]}</th>'
        f'<th>{t["intent"].split("（")[0]}</th></tr>'
    )
    return (
        f'<table class="metrics"><thead>{headers}</thead>'
        f'<tbody>{"".join(rows)}</tbody></table>'
    )


