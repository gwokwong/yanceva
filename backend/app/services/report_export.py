import re as _re

_DANGEROUS_BLOCK = _re.compile(
    r'<\s*(script|iframe|object|embed|form|link|meta)[^>]*>.*?<\s*/\s*\1\s*>',
    _re.IGNORECASE | _re.DOTALL,
)
_DANGEROUS_SELF = _re.compile(
    r'<\s*(script|iframe|object|embed|link|meta|base)[^>]*/?>',
    _re.IGNORECASE,
)
_EVENT_ATTRS = _re.compile(r"\son\w+\s*=\s*(?:\"[^\"]*\"|'[^']*'|[^\s>]+)", _re.IGNORECASE)
_JS_URL = _re.compile(r'(href|src)\s*=\s*["\']?\s*(javascript|vbscript|data\s*:\s*text)', _re.IGNORECASE)


def _sanitize_html(html: str) -> str:
    """剥除危险标签/事件属性/js 协议——LLM 输出不可信，交付物在客户浏览器渲染。"""
    html = _DANGEROUS_BLOCK.sub('', html)
    html = _DANGEROUS_SELF.sub('', html)
    html = _EVENT_ATTRS.sub('', html)
    html = _JS_URL.sub(r'\1="#"', html)
    return html


def build_deliverable_html(
    *,
    product_name: str,
    deliverable_name: str,
    order_id: str,
    report_markdown: str,
    metrics: Optional[Dict[str, Any]] = None,
    methodology: Dict[str, Any] | None = None,
    language: str = "zh",
) -> str:
    """渲染品牌化自包含 HTML 交付物（chrome 双语；正文跟随报告语言）。"""

    import markdown as markdown_lib

    t = _CHROME.get("en" if (language or "zh").lower().startswith("en") else "zh")
    methodology = methodology or {}
    metrics = metrics or {}
    series = metrics.get("series") or []
    totals = metrics.get("totals") or {}
    surveys = metrics.get("surveys") or []

    body_html = markdown_lib.markdown(
        report_markdown or "", extensions=["tables", "fenced_code"]
    )
    body_html = _sanitize_html(body_html)
    charts = _metric_charts(series, t)
    table = _metric_table(series, t)

    survey_html = ""
    if surveys:
        latest = surveys[-1]
        answers = "".join(
            f'<li><b>Agent#{r.get("agent_id")}</b>：{html_module.escape((r.get("response") or "")[:300])}</li>'
            for r in (latest.get("responses") or [])[:6]
        )
        survey_html = (
            f'<h3>{t["survey_probe"]}（{t["round"]} {latest.get("round")}，'
            f'{latest.get("sample_size")})</h3>'
            f'<ol class="survey">{answers}</ol>'
        )

    now = datetime.now().strftime("%Y-%m-%d %H:%M")
    agents = methodology.get("agents", "—")
    rounds = methodology.get("rounds", "—")
    scenario_label = methodology.get("scenario_label", "—")

